    g = pd.read_csv(DATA / "fig1_rulespace_grid.csv")
    st = pd.read_csv(DATA / "fig1_rulespace_stars.csv")

    # density is drawn as a scatter, not with imshow: the panel is a wide rectangle and
    # imshow's cells would stretch into short dashes, whereas scatter markers are drawn in
    # display space and stay circular however the axes are stretched. Semi-transparent overlap
    # then shows the density on its own.
