def _rule_table(ax, cal, W, H):
    """The complete catalogue of D1--D8 and the five nested law sets (formerly Fig. 2a, now
    Fig. 1d).

    The coordinate system is in centimetres directly: x runs 0..W to the right and y runs
    0..H downwards. Row heights therefore follow from the font size, the type does not stretch
    when the panel is widened or heightened, and any extra height becomes inter-row space.
    """
    ax.set_xticks([]); ax.set_yticks([])     # so stamp picks up the panel frame rather than
                                             # hidden ticks
    ax.axis("off")
    ax.set_xlim(0, W); ax.set_ylim(H, 0)
    xc = [W * f for f in (0.628, 0.708, 0.788, 0.868, 0.948)]
    x0, x1 = 0.0, W          # the table rules and zebra striping align exactly with the left
                             # and right edges of panel a's flow boxes
    # with the number column changed from D1--D8 to Law 1--Law 8 it is about 0.35 cm wider, so
    # the expression column moves right to 0.078W; otherwise the last character of "Law 1"
    # runs into the first character of the formula behind it.
    XR, XG = 0.014 * W, 0.078 * W            # the law-number column; the expression and gloss columns
    # the header height has to fit the three lines "L1 / contact / floor": at 0.95 the third
    # line's baseline sits exactly on the table's top rule and merges with it in print. 1.12
    # gives about 0.15 cm of clear space.
    HHEAD, HSUM, HGAP = 1.12, 0.38, 0.20     # header / per-row summary / clear space above the separator
    DY = 0.135                               # offset of the expression and gloss lines from the row centre
    HRULE = (H - HHEAD - HGAP - 2 * HSUM) / len(RULES)

    # the header labels drop to 0.32: 0.11 cm between the names and the top rule, and 0.22 cm
    # from c's axis title above -- so the labels clearly belong to the table below rather than
    # floating between the two.
    yh = 0.32
    for x, s in zip(xc, SETS):
        c = SETC[s]
        ax.text(x, yh, setlab(s, "$'$"), fontsize=9.2,
                color=c, ha="center", va="center")
        ax.text(x, yh + 0.53, SETNAME[s], fontsize=7.2, color=c, ha="center",
                va="center", linespacing=1.30)
    ax.plot([x0, x1], [HHEAD] * 2, color="#323335", lw=0.8)

    y = HHEAD
    for i, (rid, expr, gloss, member) in enumerate(RULES):
        if i % 2 == 0:
            ax.add_patch(mp.Rectangle((x0, y), x1 - x0, HRULE, fc="#EEF2F5",
                                      lw=0, zorder=0, clip_on=False))
        yc = y + HRULE / 2                  # row centre: membership markers land here
        ye = yc - DY                        # the expression line, centred symmetrically with the gloss
        ax.text(XR, ye, rid, fontsize=8.6,
                color="#212224", va="center")
        ax.text(XG, ye, expr, fontsize=8.8, color="#101113", va="center")
        ax.text(XG, yc + DY, gloss, fontsize=7.1, color="#535557",
                va="center", style="italic")
        for x, s in zip(xc, SETS):
            mk = member.get(s)
            if mk is None:
                ax.text(x, yc, "–", fontsize=7.4, color="#CACCCF", ha="center",
                        va="center")
            elif mk == "•":
                ax.scatter([x], [yc], s=30, c=SETC[s], lw=0, zorder=3,
                           transform=ax.transData)
            else:
                ax.text(x, yc, mk, fontsize=7.4, color=SETC[s], ha="center",
                        va="center")
        y += HRULE

    ax.plot([x0, x1], [y + HGAP] * 2, color="#323335", lw=0.8)
    y += HGAP
    for lab, key, fmt in [("satisfaction (experimental structures)", "sat", "{:.4f}"),
                          ("damage detection", "excl", "{:.4f}")]:
        y += HSUM
        ax.text(XG, y - 0.16, lab, fontsize=8.3, color="#323335", va="center")
